// Licence check: every production dependency of the published packages must have an
// MIT-compatible licence. `node scripts/check-licences.mjs` checks; `--write` also
// rewrites docs/licences.md. Exits 1 on any licence outside the allow list.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import process from "node:process";
import console from "node:console";

const ALLOWED = [
  "MIT",
  "MIT-0",
  "ISC",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "Apache-2.0",
  "0BSD",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "Unlicense",
  "Python-2.0",
];
// Reviewed exceptions, matched by package name. Both are Expo build tooling reached through the
// `expo` peer dependency of the RN config plugins: the user's own Expo project installs them, the
// SDK neither ships nor bundles them.
const EXCEPTIONS = new Map([
  ["caniuse-lite", "CC-BY-4.0 browser data used by Expo's Babel tooling, not shipped"],
  [
    "lightningcss",
    "MPL-2.0 (file-level copyleft) used by Expo's CSS tooling, unmodified, not shipped",
  ],
]);
const nameOf = (id) => id.slice(0, id.lastIndexOf("@"));

// Packages the SDK ships or depends on at run time; dev tooling is not shipped.
const PACKAGES = ["@openblah/core", "@openblah/web", "@openblah/react-native"];

const split = (l) =>
  String(l)
    .replace(/[()*]/g, "")
    .split(/\s+(?:OR|AND)\s+/i)
    .map((s) => s.trim());
// An "OR" expression passes when any option is allowed; "AND" needs all.
const ok = (expr) => {
  const e = String(expr).replace(/^\(|\)$/g, "");
  if (/\sOR\s/i.test(e)) return split(e).some((x) => ALLOWED.includes(x));
  return split(e).every((x) => ALLOWED.includes(x));
};

const rows = new Map();
for (const pkg of PACKAGES) {
  const out = execFileSync(
    "pnpm",
    [
      "--filter",
      pkg,
      "exec",
      "license-checker-rseidelsohn",
      "--production",
      "--json",
      "--start",
      ".",
    ],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, cwd: process.cwd() },
  );
  const json = JSON.parse(out.slice(out.indexOf("{")));
  for (const [id, info] of Object.entries(json)) {
    if (id.startsWith("@openblah/")) continue;
    rows.set(id, String(info.licenses));
  }
}

const bad = [...rows].filter(([id, l]) => !ok(l) && !EXCEPTIONS.has(nameOf(id)));
const sorted = [...rows].sort(([a], [b]) => a.localeCompare(b));

if (process.argv.includes("--write")) {
  const byLicence = new Map();
  for (const [, l] of rows) byLicence.set(l, (byLicence.get(l) ?? 0) + 1);
  const md = [
    "# Dependency licences",
    "",
    "Generated by `pnpm licences --write` (`scripts/check-licences.mjs`). Covers the production dependencies of `@openblah/core`, `@openblah/web` and `@openblah/react-native`. CI fails on any licence that is not MIT-compatible.",
    "",
    `Allowed: ${ALLOWED.join(", ")}.`,
    "",
    "## Reviewed exceptions",
    "",
    "Outside the allow list, accepted on purpose:",
    "",
    ...[...EXCEPTIONS].map(([n, why]) => `- \`${n}\`: ${why}.`),
    "",
    "## Summary",
    "",
    "| Licence | Packages |",
    "| --- | --- |",
    ...[...byLicence].sort().map(([l, n]) => `| ${l} | ${n} |`),
    "",
    "## All packages",
    "",
    "| Package | Licence |",
    "| --- | --- |",
    ...sorted.map(([id, l]) => `| ${id} | ${l} |`),
    "",
  ].join("\n");
  writeFileSync("docs/licences.md", md);
}

if (bad.length) {
  console.error("Licences that are not on the allow list:");
  for (const [id, l] of bad) console.error(`  ${id}: ${l}`);
  process.exit(1);
}
console.log(`Licence check passed: ${rows.size} packages.`);
