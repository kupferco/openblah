/**
 * Guess whether a transcript is English or Portuguese. Returns `fallback`
 * (normally the language of the previous turn) when the text is too short or
 * ambiguous. A word-list vote keeps this free and instant; Portuguese accents
 * count extra because English has none.
 */
export function detectLanguage(text: string, fallback: SpokenLanguage = "en"): SpokenLanguage {
  const words = text.toLowerCase().match(/[\p{L}']+/gu) ?? [];
  if (words.length === 0) return fallback;
  let pt = 0;
  let en = 0;
  for (const w of words) {
    if (PT_WORDS.has(w)) pt++;
    if (EN_WORDS.has(w)) en++;
    if (/[ãõçáéíóúâêô]/u.test(w)) pt += 1;
  }
  if (pt === en) return fallback;
  return pt > en ? "pt" : "en";
}
